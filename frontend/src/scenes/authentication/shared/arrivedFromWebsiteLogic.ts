import { LogicWrapper, MakeLogicType, actions, afterMount, kea, path, reducers } from 'kea'

// Website origin is configured by the Flind operator; no inherited third-party
// marketing domain is ever trusted by default.
export function isWebsiteReferrer(
    referrer: string,
    websiteHostname: string = import.meta.env?.VITE_FLIND_WEBSITE_HOST || ''
): boolean {
    if (!referrer || !websiteHostname || !/^[a-z0-9][a-z0-9.-]*[a-z0-9]$/.test(websiteHostname)) {
        return false
    }
    if (websiteHostname.includes('..') || websiteHostname.split('.').some((label) => label.startsWith('-') || label.endsWith('-'))) {
        return false
    }
    try {
        const url = new URL(referrer)
        return url.protocol === 'https:' && !url.username && !url.password && !url.port && url.hostname === websiteHostname
    } catch {
        return false
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface arrivedFromWebsiteLogicValues {
    arrivedFromWebsite: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface arrivedFromWebsiteLogicActions {
    setArrivedFromWebsite: (arrivedFromWebsite: boolean) => { arrivedFromWebsite: boolean }
}

export type arrivedFromWebsiteLogicType = MakeLogicType<arrivedFromWebsiteLogicValues, arrivedFromWebsiteLogicActions>

export const arrivedFromWebsiteLogic: LogicWrapper<arrivedFromWebsiteLogicType> = kea<arrivedFromWebsiteLogicType>([
    path(['scenes', 'authentication', 'shared', 'arrivedFromWebsiteLogic']),
    actions({
        setArrivedFromWebsite: (arrivedFromWebsite: boolean) => ({ arrivedFromWebsite }),
    }),
    reducers({
        arrivedFromWebsite: [
            false,
            {
                setArrivedFromWebsite: (_, { arrivedFromWebsite }) => arrivedFromWebsite,
            },
        ],
    }),
    afterMount(({ actions }) => {
        actions.setArrivedFromWebsite(isWebsiteReferrer(document.referrer))
    }),
])
